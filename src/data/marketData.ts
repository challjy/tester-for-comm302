// Helper to generate realistic candle bars for chart view
export function generateCandles(basePrice: number, count: number = 30): { time: string; open: number; high: number; low: number; close: number }[] {
  const candles = [];
  let curr = basePrice * 0.95;
  const now = new Date();

  for (let i = count; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 3600 * 1000 * 4);
    const timeStr = `${d.getHours().toString().padStart(2, '0')}:00`;
    const delta = (Math.random() - 0.48) * (basePrice * 0.015);
    const open = curr;
    const close = +(curr + delta).toFixed(2);
    const high = +(Math.max(open, close) + Math.random() * (basePrice * 0.008)).toFixed(2);
    const low = +(Math.min(open, close) - Math.random() * (basePrice * 0.008)).toFixed(2);
    candles.push({
      time: timeStr,
      open,
      high,
      low,
      close
    });
    curr = close;
  }
  return candles;
}
